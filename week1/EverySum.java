package week1;
public class EverySum {
    public static void main(String[] args) {
        int sum;
        int n;
        for (int i = 1; i < 50; i++) {
            sum = 0;
            for (int i = 1; i <= n; i++) {
                sum += i;
            }

            System.out.println("sum of 1 to" + n + "is" + sum);
        }
    }
}
